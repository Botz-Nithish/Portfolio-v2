// Extracts display-type outlines from Archivo into src/gfx/glyphs.gen.ts.
// Display type is drawn art, so words are stored as paths that can be extruded and animated.
import * as fontkit from "fontkit";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// fontkit cannot instance variable axes from WOFF2, so this tool reads the source TTFs.
const fonts = resolve(root, "tools/fonts");
const upright = fontkit.openSync(resolve(fonts, "Archivo.ttf"));
const italic = fontkit.openSync(resolve(fonts, "Archivo-Italic.ttf"));

// Word, font, variation axes. Output units are 1000 per em, with y pointing down.
const heavy = { wght: 900, wdth: 125 };
const WORDS = [
  ...[
    "CODE", "CRAFT",
    "2004", "2022", "2024", "2025", "2026",
    "ZINGBOT", "WMS", "PIXELPIPE", "V-MEET", "NEURORYTHM", "SCHOLAR", "KALLOS", "FINSOL",
    "DISCOVER", "ARCHITECT", "BUILD", "SHIP",
    "LET’S", "TALK.",
    "LANGUAGES", "FRONT-END", "BACK-END", "& APIS", "DATA", "& CLOUD", "TOOLS", "& PROCESS",
    "MY LIFE", "JOURNEY", "PROJECTS", "PROCESS", "SKILLS",
  ].map((word) => [word, upright, heavy]),
  ["MEETS", italic, { wght: 300, wdth: 62 }],
  ["SEE?", italic, { wght: 300, wdth: 62 }],
  ["MY", italic, { wght: 300, wdth: 62 }],
  // A fourth entry stores the cut under its own name.
  ["PROJECTS", upright, { wght: 900, wdth: 62 }, "PROJECTS TALL"],
  ["PROCESS", upright, { wght: 900, wdth: 62 }, "PROCESS TALL"],
];

const round = (n) => Math.round(n * 10) / 10;

function toD(path, k) {
  const pt = (x, y) => `${round(x * k)} ${round(-y * k)}`;
  return path.commands
    .map(({ command, args: a }) => {
      if (command === "moveTo") return `M${pt(a[0], a[1])}`;
      if (command === "lineTo") return `L${pt(a[0], a[1])}`;
      if (command === "quadraticCurveTo") return `Q${pt(a[0], a[1])} ${pt(a[2], a[3])}`;
      if (command === "bezierCurveTo") return `C${pt(a[0], a[1])} ${pt(a[2], a[3])} ${pt(a[4], a[5])}`;
      return "Z";
    })
    .join("");
}

const out = {};
for (const [word, font, axes, name = word] of WORDS) {
  const inst = font.getVariation(axes);
  const k = 1000 / font.unitsPerEm;
  const run = inst.layout(word);
  let x = 0;
  const glyphs = run.glyphs.map((g, i) => {
    const entry = { ch: word[i], x: round(x * k), adv: round(run.positions[i].xAdvance * k), d: toD(g.path, k) };
    x += run.positions[i].xAdvance;
    return entry;
  });
  out[name] = { width: round(x * k), capHeight: round(font.capHeight * k), glyphs };
}

// The preloader paints before any script or font has arrived, so the O it fills lives in index.html.
function eyeDefs() {
  const glyph = upright.getVariation(heavy).layout("O").glyphs[0];
  const k = 1000 / upright.unitsPerEm;
  const { minX, minY, maxX, maxY } = glyph.path.bbox;
  const [x, y, w, h] = [minX * k, -maxY * k, (maxX - minX) * k, (maxY - minY) * k].map(round);
  const outer = toD(glyph.path, k).match(/M[^M]*/g)[0];
  const scale = `scale(${(1 / w).toFixed(6)} ${(1 / h).toFixed(6)}) translate(${-x} ${-y})`;
  return [
    `<clipPath id="eye-clip" clipPathUnits="objectBoundingBox"><path transform="${scale}" d="${outer}" /></clipPath>`,
    `<path id="eye-line" transform="translate(${-x} ${-y})" d="${outer}" />`,
    `<!-- eye: ${w} ${h} -->`,
  ].join("\n        ");
}

const html = resolve(root, "index.html");
writeFileSync(
  html,
  readFileSync(html, "utf8").replace(
    /(<!-- eye:start -->)[\s\S]*?(<!-- eye:end -->)/,
    `$1\n        ${eyeDefs()}\n        $2`,
  ),
);

const body = `// Generated by tools/glyphs.mjs. Do not edit by hand.
export interface Glyph { ch: string; x: number; adv: number; d: string }
export interface Word { width: number; capHeight: number; glyphs: Glyph[] }
export const WORDS: Record<string, Word> = ${JSON.stringify(out, null, 1)};
`;
writeFileSync(resolve(root, "src/gfx/glyphs.gen.ts"), body);
